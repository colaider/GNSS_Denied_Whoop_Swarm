# makeHeader - weights.npz (from train.py) -> whoopCTRL/M4/NN/headers/ResidualNetWeights.h
# Every weight and bias as an nn::Vec / nn::Mat (NetTypes.h). Run after every training: python makeHeader.py
import datetime
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
WEIGHTS = os.path.join(HERE, "weights.npz")
OUT = os.path.join(HERE, "..", "..", "whoopCTRL", "M4", "NN", "headers", "ResidualNetWeights.h")


def num(x):
    return f"{float(x): .8e}f"


def vec(name, v, comment=""):
    return f"static const Vec<{len(v)}> {name} = {{{{{', '.join(num(x) for x in v)}}}}};{'   // ' + comment if comment else ''}\n"


def mat(name, M, comment=""):
    rows = ",\n".join("    {" + ", ".join(num(x) for x in r) + "}" for r in M)
    return f"static const Mat<{M.shape[0]}, {M.shape[1]}> {name} = {{{{   // {comment}\n{rows}\n}}}};\n"


def main():
    w = np.load(WEIGHTS)
    inputs = [str(s) for s in w["inputs"]]
    r2 = 1 - float(w["testMse"]) / float(w["baseMse"])
    text = (
        "#pragma once\n"
        "// ResidualNetWeights - GENERATED by collectedData/NeuroFligh/makeHeader.py, do not edit: train again.\n"
        f"// {datetime.datetime.now():%Y-%m-%d %H:%M}, test MSE {float(w['testMse']):.4f}, R2 {r2:.3f}\n"
        "//   x    = normalise([" + ", ".join(inputs) + "], inputMean, inputStd)\n"
        "//   h1   = tanh(W1 x + b1),  h2 = tanh(W2 h1 + b2)\n"
        "//   rHat = dot(theta0, withOne(h2))      residual z acceleration, m/s^2 (theta0: start of the online theta)\n\n"
        '#include "NetTypes.h"\n\n'
        "namespace nn {\nnamespace residual {\n\n"
        + vec("inputMean", w["mean"], ", ".join(inputs))
        + vec("inputStd", w["std"])
        + "\n" + mat("W1", w["W1"], f"{w['W1'].shape[1]} inputs -> {w['W1'].shape[0]} neurons")
        + vec("b1", w["b1"])
        + "\n" + mat("W2", w["W2"], f"{w['W2'].shape[1]} -> {w['W2'].shape[0]}")
        + vec("b2", w["b2"])
        + "\n" + vec("theta0", w["theta"], "last layer, the last entry is the constant feature's")
        + "\n}  // namespace residual\n}  // namespace nn\n"
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
