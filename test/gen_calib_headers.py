# Convert the calibration results into C++ headers for the Nicla firmware.
#   calibration.npz  (calib_run.py)  -> camera_calib.h
#   imu_calib.json   (imu_calib.py)  -> imu_calib.h
# The headers are data only (constexpr values), generated - don't edit them by hand,
# re-run this script after every new calibration.
#
# python gen_calib_headers.py                       (files next to this script)
# python gen_calib_headers.py --cam ../whoopCTRL/calibartion/calibration.npz
#                             --imu ../whoopCTRL/calibartion/imu_calib.json --out out_dir
# pip install numpy

import argparse
import datetime
import hashlib
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))

# GC2145 modes in the Arduino driver: width -> (height, subsample s, window x0, window y0)
MODES = {160: (120, 4, 480, 360), 320: (240, 3, 320, 240), 640: (480, 2, 160, 120)}


def f(x):
    """C++ float literal with enough digits."""
    x = float(x)
    if not np.isfinite(x):
        raise SystemExit(f"bad value in calibration: {x}")
    s = f"{x:.9g}"
    if "." not in s and "e" not in s:
        s += ".0"                                  # "1f" is not valid C++, "1.0f" is
    return s + "f"


def arr(v):
    return "{" + ", ".join(f(x) for x in np.ravel(v)) + "}"


def source_info(path):
    digest = hashlib.sha256(open(path, "rb").read()).hexdigest()[:12]
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    return (f"// Generated by gen_calib_headers.py on {now} - DO NOT EDIT.\n"
            f"// source: {os.path.basename(path)}  sha256: {digest}\n")


def convert(K, cal_w, new_w):
    """Intrinsics from the calibrated mode to another mode (fallback if the npz lacks K_<w>)."""
    _, s1, x1, y1 = MODES[cal_w]
    _, s2, x2, y2 = MODES[new_w]
    K2 = K.copy()
    K2[0, 0], K2[1, 1] = K[0, 0] * s1 / s2, K[1, 1] * s1 / s2
    K2[0, 2] = (x1 + s1 * K[0, 2] - x2) / s2
    K2[1, 2] = (y1 + s1 * K[1, 2] - y2) / s2
    return K2


def camera_header(path):
    d = np.load(path)
    for key in ("camera_matrix", "dist_coeff"):
        if key not in d.files:
            raise SystemExit(f"{path}: missing '{key}'")
    K = d["camera_matrix"]
    dist = np.ravel(d["dist_coeff"])
    dist = np.pad(dist, (0, max(0, 5 - len(dist))))[:5]      # k1 k2 p1 p2 k3
    cal_w = int(d["cal_width"]) if "cal_width" in d.files else int(d["image_size"][0])
    if K[0, 0] <= 0 or K[1, 1] <= 0:
        raise SystemExit(f"{path}: focal length must be positive")

    lines = [source_info(path),
             "#pragma once\n",
             "// Camera intrinsics per GC2145 mode. Each mode is a different centred crop of",
             "// the sensor, so fx/fy/cx/cy differ per mode; distortion is the same for all.",
             "// Pixel -> normalised: x = (u - cx) / fx,  y = (v - cy) / fy, then undistort with CAM_DIST.\n",
             "namespace calib {\n",
             "struct CameraIntrinsics {",
             "  float fx, fy, cx, cy;   // pixels",
             "  int width, height;",
             "};\n",
             f"constexpr int CAM_CAL_WIDTH = {cal_w};          // mode the images were taken in\n",
             "// OpenCV order: k1, k2, p1, p2, k3",
             f"constexpr float CAM_DIST[5] = {arr(dist)};\n"]
    for w, (h, *_rest) in sorted(MODES.items()):
        Kw = d[f"K_{w}"] if f"K_{w}" in d.files else convert(K, cal_w, w)
        lines.append(f"constexpr CameraIntrinsics CAM_{w}x{h} = "
                     f"{{{f(Kw[0, 0])}, {f(Kw[1, 1])}, {f(Kw[0, 2])}, {f(Kw[1, 2])}, {w}, {h}}};")
    lines.append("\n}  // namespace calib\n")
    return "\n".join(lines)


def imu_header(path):
    c = json.load(open(path))
    need = ["gyro_bias_dps", "gyro_scale", "accel_bias_g", "accel_scale"]
    missing = [k for k in need if k not in c]
    if missing:
        raise SystemExit(f"{path}: missing {missing}")
    has_fit = "accel_M" in c and "accel_bias_fit_g" in c
    M = np.array(c["accel_M"]) if has_fit else np.eye(3)
    b_fit = np.array(c["accel_bias_fit_g"]) if has_fit else np.zeros(3)
    rows = ",\n    ".join(arr(r) for r in M)

    lines = [source_info(path),
             "#pragma once\n",
             "// LSM6DSOX calibration. Valid only for the settings below - recalibrate if you",
             "// change the data rate or ranges.\n",
             "namespace calib {\n",
             f"constexpr const char* IMU_SETTINGS = \"{c.get('settings', 'unknown')}\";",
             f"constexpr float IMU_CAL_TEMP_C = {f(c.get('temp_C', 0))};   // 0 = not recorded\n",
             "// Gyro: w = (w_raw - GYRO_BIAS_DPS) * GYRO_SCALE   [deg/s]",
             "// The bias drifts with temperature: re-measure it at power-up, use this as fallback.",
             f"constexpr float GYRO_BIAS_DPS[3]  = {arr(c['gyro_bias_dps'])};",
             f"constexpr float GYRO_SCALE[3]     = {arr(c['gyro_scale'])};",
             f"constexpr float GYRO_NOISE_DPS[3] = {arr(c.get('gyro_noise_dps', [0, 0, 0]))};\n",
             "// Accel, simple 6-side model: a = (a_raw - ACC_BIAS_G) / ACC_SCALE   [g]",
             f"constexpr float ACC_BIAS_G[3] = {arr(c['accel_bias_g'])};",
             f"constexpr float ACC_SCALE[3]  = {arr(c['accel_scale'])};\n",
             "// Accel, full fit (preferred when ACC_HAS_FIT): a = ACC_M * (a_raw - ACC_BIAS_FIT_G)",
             f"constexpr bool  ACC_HAS_FIT = {'true' if has_fit else 'false'};",
             f"constexpr float ACC_BIAS_FIT_G[3] = {arr(b_fit)};",
             f"constexpr float ACC_M[3][3] = {{\n    {rows}}};",
             "\n}  // namespace calib\n"]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cam", default=os.path.join(HERE, "calibration.npz"))
    ap.add_argument("--imu", default=os.path.join(HERE, "imu_calib.json"))
    ap.add_argument("--out", default=HERE)
    a = ap.parse_args()

    os.makedirs(a.out, exist_ok=True)
    for name, text in (("camera_calib.h", camera_header(a.cam)), ("imu_calib.h", imu_header(a.imu))):
        p = os.path.join(a.out, name)
        with open(p, "w", newline="\n") as fh:
            fh.write(text)
        print("wrote", p)


if __name__ == "__main__":
    main()
